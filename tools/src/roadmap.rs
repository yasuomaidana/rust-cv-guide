//! The roadmap page: every OpenCV tutorial and module with its status. Implemented tutorials link to their page.

use crate::generate::{BLOB, Page, TREE, is_implemented, status_of};
use crate::model::{Catalog, Coverage, Entry, Status, Tutorial};
use std::collections::BTreeMap;

fn tally(statuses: &[Status]) -> Vec<usize> {
    let count = |wanted: &Status| statuses.iter().filter(|s| *s == wanted).count();
    Status::ALL.iter().map(count).collect()
}

fn row(cells: &[String]) -> String {
    format!("| {} |", cells.join(" | "))
}

fn note(entry: Option<&Entry>) -> String {
    entry
        .and_then(|e| e.reason.clone())
        .unwrap_or_default()
        .replace('|', "\\|")
}

fn tutorial_row(tutorial: &Tutorial, entry: Option<&Entry>) -> String {
    let (status, _) = status_of(entry);
    let title = tutorial.title.replace('|', "\\|");
    let name = if is_implemented(status) {
        format!("[{title}](opencv/{}/{}.md)", tutorial.section, tutorial.id)
    } else {
        format!("{title} ([OpenCV]({BLOB}{}))", tutorial.source)
    };
    row(&[name, status.label().into(), note(entry)])
}

fn summary(modules: &[Status], tutorials: &[Status]) -> Vec<String> {
    let mut lines = vec!["| Status | Modules | Tutorials |\n|---|---|---|".to_string()];
    let (m, t) = (tally(modules), tally(tutorials));
    for (i, status) in Status::ALL.iter().enumerate() {
        lines.push(row(&[
            status.label().into(),
            m[i].to_string(),
            t[i].to_string(),
        ]));
    }
    lines.push(row(&[
        "**Total**".into(),
        modules.len().to_string(),
        tutorials.len().to_string(),
    ]));
    lines
}

fn module_table(catalog: &Catalog, coverage: &Coverage) -> Vec<String> {
    let mut lines = vec!["\n## Modules\n\n| Module | Status | Note |\n|---|---|---|".to_string()];
    for m in &catalog.modules {
        let entry = coverage.modules.get(&m.name);
        let name = format!("[{}]({TREE}{})", m.title, m.source);
        lines.push(row(&[name, status_of(entry).0.label().into(), note(entry)]));
    }
    lines
}

/// `docs/roadmap.md`.
pub fn page(catalog: &Catalog, coverage: &Coverage) -> Page {
    let mut sections: BTreeMap<&str, Vec<&Tutorial>> = BTreeMap::new();
    for t in &catalog.tutorials {
        sections.entry(t.section.as_str()).or_default().push(t);
    }
    let status = |t: &&Tutorial| status_of(coverage.tutorials.get(&t.id)).0;
    let all: Vec<Status> = sections.values().flatten().map(status).collect();
    let modules: Vec<Status> = catalog
        .modules
        .iter()
        .map(|m| status_of(coverage.modules.get(&m.name)).0)
        .collect();
    let mut lines = vec![
        "---\ntitle: Roadmap\nsidebar_position: 2\n---\n".to_string(),
        "What this guide covers and what it could cover next. Only the tutorials marked `covered` or `partial` have a page, with code that is compiled and tested; the others are listed so you can see the gaps. Generated by `cvg-tools generate` from `catalog/`; do not edit by hand.\n".to_string(),
    ];
    lines.extend(summary(&modules, &all));
    for (name, tutorials) in &sections {
        lines.push(format!(
            "\n## {name}\n\n| Tutorial | Status | Note |\n|---|---|---|"
        ));
        for t in tutorials {
            lines.push(tutorial_row(t, coverage.tutorials.get(&t.id)));
        }
    }
    lines.extend(module_table(catalog, coverage));
    Page {
        path: "docs/roadmap.md".into(),
        content: lines.join("\n") + "\n",
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::model::fixtures::{catalog, coverage, entry};
    use rstest::rstest;

    fn text(status: Status, reason: Option<&str>) -> String {
        let mut cov = coverage(status, &["ndarray"]);
        cov.tutorials.get_mut("tutorial_mat").unwrap().reason = reason.map(Into::into);
        page(&catalog(), &cov).content
    }

    #[rstest]
    #[case(
        Status::Covered,
        "[The \"Mat\" class](opencv/core/tutorial_mat.md) | covered |"
    )]
    #[case(
        Status::Partial,
        "[The \"Mat\" class](opencv/core/tutorial_mat.md) | partial |"
    )]
    #[case(
        Status::Gap,
        "The \"Mat\" class ([OpenCV](https://github.com/opencv/opencv/blob/5.1.0/doc/tutorials/core/mat.markdown)) | gap |"
    )]
    #[case(Status::Covered, "| covered | 1 | 1 |")]
    #[case(
        Status::Covered,
        "| [Core](https://github.com/opencv/opencv/tree/5.1.0/modules/core) | covered |"
    )]
    fn renders_expected_rows(#[case] status: Status, #[case] expected: &str) {
        let text = text(status, None);
        assert!(text.contains(expected), "{text}");
    }

    #[test]
    fn reasons_are_shown_with_pipes_escaped() {
        assert!(text(Status::Gap, Some("a | b")).contains("| a \\| b |"));
    }

    #[test]
    fn items_without_an_entry_are_unreviewed() {
        let mut cov = coverage(Status::Covered, &[]);
        cov.tutorials.clear();
        cov.modules.insert("core".into(), entry(Status::Gap, &[]));
        let page = page(&catalog(), &cov).content;
        assert!(
            page.contains("| unreviewed |") && page.contains("| 0 | 1 |"),
            "{page}"
        );
    }
}
